// ─── Sync ───

export interface SyncConfig {
  enabled: boolean
  syncPath: string
  lastSyncedAt: string | null
  autoSync: boolean
}

/**
 * Why a sync read declined to proceed. `missing` means the share has no payload
 * yet (nothing to lose — safe to seed it); the other two mean we could not read
 * what is there, so writing over it would discard remote-only data.
 */
export type SyncSkipReason = 'missing' | 'unreadable' | 'unreachable'

export interface SyncResult {
  success: boolean
  message: string
  exportedAt?: string
  skipReason?: SyncSkipReason
}

export interface SyncPreferences {
  theme: string
  viewMode: string
  sidebarCollapsed: boolean
  activeTab: string
  /**
   * Reminder behaviour settings (from AppPreferences), synced alongside the UI
   * ones because they *have* to agree between machines.
   *
   * With machine A on a 'high' threshold and machine B on 'urgent', a high
   * priority task made an auto reminder on A and none on B: B's next edit of that
   * task removed the reminder, A's next export re-supplied it, and the two
   * machines fought over it indefinitely. The automation can only be
   * deterministic if its inputs are the same everywhere.
   *
   * OPTIONAL: a payload written before this shipped has none of these keys, and
   * that must mean "leave my settings alone", not "reset them to defaults".
   * Filled in by exportData from the main process's own prefs — the renderer does
   * not own them.
   */
  reminderPriorityThreshold?: TaskPriority
  reminderDefaultLeadMin?: number
  reminderDefaultIntensity?: ReminderIntensity
  reminderDefaultEscalateMin?: number | null
}

export interface SyncNowResult {
  success: boolean
  message: string
  importedNewData: boolean
  preferences: SyncPreferences | null
  exportedAt?: string
}

// ─── App Preferences (tray / autostart) ───

export interface AppPreferences {
  /** Closing the window hides to the tray instead of quitting. Default true. */
  closeToTray: boolean
  /** Launch at Windows login (hidden, straight to tray). */
  openAtLogin: boolean
  /**
   * Tasks at or above this priority with a future due date get an automatic
   * reminder. Default 'high' (so high and urgent qualify).
   */
  reminderPriorityThreshold: TaskPriority
  /** Minutes before the due date an automatic reminder fires. */
  reminderDefaultLeadMin: number
  /** Starting tier for new reminders. */
  reminderDefaultIntensity: ReminderIntensity
  /** Minutes before an unacknowledged reminder climbs a rung; null = never. */
  reminderDefaultEscalateMin: number | null
}

// ─── Persistence Failures (main → renderer) ───

export type PersistenceIssueKind =
  /** A stored file did not parse. */
  | 'corrupt'
  /** A write could not be completed. */
  | 'write-failed'
  /** A path could not be reached at all — typically the sync share being offline. */
  | 'unreachable'
  /**
   * A piece of the app could not start (tray icon, global hotkey). `file` holds
   * a human-readable subject rather than a path.
   */
  | 'unavailable'

export interface PersistenceIssue {
  /** Monotonic id so a queued issue delivered twice collapses in the UI. */
  id: number
  kind: PersistenceIssueKind
  file: string
  detail: string
}

