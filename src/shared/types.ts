// ─── Reminders Domain ───

/** NULL freq means one-off; these are the repeating shapes. */
export type ReminderFreq = 'daily' | 'weekly' | 'monthly' | 'yearly'

/** The escalation ladder, in order. `intensity` is where a firing STARTS. */
export type ReminderIntensity = 'toast' | 'popup' | 'blackout'

export type ReminderEntityType = 'task' | 'note'

export type ReminderOccurrenceState =
  | 'pending'
  | 'fired'
  | 'snoozed'
  | 'acknowledged'
  | 'missed'
  | 'skipped'

export interface Reminder {
  id: number
  /** Stable cross-machine identity used by sync. Generated by the database. */
  sync_id: string
  title: string
  body: string | null
  entity_type: ReminderEntityType | null
  entity_id: number | null
  /** ISO instant of the first firing; the anchor all recurrence derives from. */
  fire_at: string
  freq: ReminderFreq | null
  interval: number
  /** Weekly only: comma-separated 0-6, 0 = Sunday. */
  byweekday: string | null
  lead_time_min: number
  intensity: ReminderIntensity
  escalate_after_min: number | null
  sound: string | null
  auto_created: number
  enabled: number
  created_at: string
  updated_at: string
}

export interface ReminderOccurrence {
  id: number
  reminder_id: number
  fire_at: string
  state: ReminderOccurrenceState
  current_tier: ReminderIntensity | null
  fired_at: string | null
  acknowledged_at: string | null
  snoozed_until: string | null
  snooze_count: number
}

export interface ReminderWithMeta extends Reminder {
  /** Soonest pending/snoozed occurrence, or null when nothing is scheduled. */
  next_occurrence: ReminderOccurrence | null
  /** A firing (or overdue-unacknowledged) occurrence, if there is one. */
  active_occurrence: ReminderOccurrence | null
  missed_count: number
  /** Title of the linked task/note, when the link still resolves. */
  entity_title: string | null
}

/** Which section of the Reminders tab a reminder belongs in. */
export type ReminderBucket = 'firing' | 'upcoming' | 'missed' | 'disabled'

/**
 * Outcome of "Reset to automatic" — handing a reminder that a timing edit detached
 * back to its task's due date.
 *
 * `message` is present when the reset was refused, and also when it succeeded with
 * a caveat worth saying out loud (the task no longer qualifies, so the reminder is
 * now following it *and* switched off).
 */
export interface ReminderResetResult {
  ok: boolean
  message?: string
  reminder: ReminderWithMeta | null
}

/** Everything the renderer supplies when creating or editing a reminder. */
export interface ReminderInput {
  title: string
  body: string | null
  fire_at: string
  freq: ReminderFreq | null
  interval: number
  byweekday: number[] | null
  lead_time_min: number
  intensity: ReminderIntensity
  escalate_after_min: number | null
  sound: string | null
  entity_type: ReminderEntityType | null
  entity_id: number | null
}

export interface ReminderAlertItem {
  title: string
  fire_at: string
}

/** What an alert window renders. Pushed from main; never derived in the renderer. */
export interface ReminderAlertPayload {
  kind: 'single' | 'digest'
  occurrence_id: number | null
  reminder_id: number | null
  title: string
  body: string | null
  tier: ReminderIntensity
  fire_at: string
  /** Fired late (missed while the app was closed/asleep). */
  late: boolean
  /** How many further firings are waiting behind this one. */
  queued_count: number
  /** Digest contents; empty for a single alert. */
  items: ReminderAlertItem[]
  /** base64 data URI — a file:// path would be blocked by the renderer CSP. */
  sound_data_uri: string | null
  loop_sound: boolean
}

/** Snooze presets offered by the alert window and the Reminders tab. */
export type ReminderSnoozeChoice = 5 | 10 | 30 | 60 | 'tomorrow'

